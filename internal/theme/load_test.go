func writeTheme(t *testing.T, dir, name, content string) string {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.WriteFile(p, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
	return p
}
func mustLoad(t *testing.T, path string) *Theme {
	t.Helper()
	return mustLoadKind(t, path, "vs-dark")
}

func mustLoadKind(t *testing.T, path, kind string) *Theme {
	t.Helper()
	data, err := loadSource(filepath.ToSlash(path), kind, readThemeFile)
	if err != nil {
		t.Fatal(err)
	}
	return data.theme(path)
}

func TestJSONCIncludesColorsAndTokens(t *testing.T) {
	dir := t.TempDir()
	writeTheme(t, dir, "base.json", `{
 "colors":{"editor.background":"#123", "editor.foreground":"#abcdef", "sideBar.background":"#444444"},
 "tokenColors":[{"scope":"comment", "settings":{"foreground":"#123456","fontStyle":"italic"}},
 {"scope":"string", "settings":{"foreground":"#112233"}}]}`)
	name := writeTheme(t, dir, "theme.jsonc", `{
 // https://example.com/a//b and trailing commas are valid JSONC
 "name":"URL // /* name */", "type":"dark", "include":"./base.json",
 "colors":{"sideBar.background":"default", "editor.selectionBackground":"#f008",},
 "tokenColors":[{"scope":["comment"],"settings":{"foreground":"#fed", "fontStyle":"",}},],
 }`)
	th := mustLoadKind(t, name, "vs")
	if !th.IsLight() || th.Name != "URL // /* name */" {
		t.Fatalf("metadata: %+v", th)
	}
	p := th.Palette()
	if p.Background != "#112233" || p.Foreground != "#ABCDEF" || p.Panel != "#F3F3F3" || p.EditorSelection != "#FF000088" || Composite(p.EditorSelection, p.Background) != "#901018" {
		t.Fatalf("palette: %+v", p)
	}
	if got := th.Resolve([]string{"source.go", "comment.line.go"}); got.Color != "#FFEEDD" || got.Font != 0 {
		t.Fatalf("derived comment: %+v", got)
	}
	if got := th.Resolve([]string{"source.go", "string.quoted.go"}); got.Color != "#112233" {
		t.Fatalf("inherited string: %+v", got)
	}
}

func TestInvalidThemesAreErrors(t *testing.T) {
	dir := t.TempDir()
	for _, input := range []string{`[]`, `null`, `{"tokenColors":12}`, `{/*`, `{"colors":[]}`, `{"include":"missing.json"}`} {
		name := writeTheme(t, dir, "invalid.json", input)
		if _, err := loadSource(filepath.ToSlash(name), "vs-dark", readThemeFile); err == nil {
			t.Errorf("accepted %s", input)
		}
	}
	writeTheme(t, dir, "a.json", `{"include":"b.json"}`)
	name := writeTheme(t, dir, "b.json", `{"include":"a.json"}`)
	if _, err := loadSource(filepath.ToSlash(name), "vs-dark", readThemeFile); err == nil || !strings.Contains(err.Error(), "cycle") {
		t.Fatalf("include cycle: %v", err)
	}
}

func TestTextMateFileAndExternalTokenColors(t *testing.T) {
	dir := t.TempDir()
	plist := `<?xml version="1.0"?><!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd"><plist version="1.0"><dict>
 <key>name</key><string>Legacy</string><key>settings</key><array>
 <dict><key>settings</key><dict><key>foreground</key><string>#123456</string><key>background</key><string>#abcdef</string></dict></dict>
 <dict><key>scope</key><string>comment, string</string><key>settings</key><dict><key>foreground</key><string>#ABC</string><key>fontStyle</key><string>bold underline strikethrough</string></dict></dict>
 </array></dict></plist>`
	file := writeTheme(t, dir, "tokens.tmTheme", plist)
	th := mustLoad(t, file)
	if th.Palette().Background != "#ABCDEF" || th.Resolve([]string{"string.quoted"}).Font != Bold|Underline|Strikethrough {
		t.Fatalf("legacy theme: %+v", th)
	}
	file = writeTheme(t, dir, "external.json", `{"tokenColors":"./tokens.tmTheme"}`)
	th = mustLoad(t, file)
	if th.Palette().Foreground != "#123456" || th.Resolve([]string{"comment.line"}).Color != "#AABBCC" {
		t.Fatal("external tmTheme not converted")
	}
}

func TestBuiltinsUseIndependentUIAndSyntax(t *testing.T) {
	if len(BuiltinIDs) != 10 {
		t.Fatalf("expected the 10 VS Code default themes, got %d", len(BuiltinIDs))
	}
	for _, id := range BuiltinIDs {
		th := Builtin(id)
		spec := builtinThemes[id]
		if th.Name == "" || th.Palette().Foreground == "" || th.Type != spec.kind ||
			th.VSCodeID != spec.vscodeID || !isBundledTheme(defaultExtensionID, th.VSCodeID) {
			t.Fatalf("invalid builtin: %s", id)
		}
	}

	if Builtin("dark_modern").Palette().Background == Builtin("dark_plus").Palette().Background {
		t.Fatal("Dark+ borrowed Modern UI overrides")
	}
	if Builtin("dark_plus").Resolve([]string{"entity.name.function.go"}).Color == Builtin("dark_vs").Resolve([]string{"entity.name.function.go"}).Color {
		t.Fatal("Dark VS borrowed Dark+ rules")
	}
	if Builtin("dark_modern").Palette().AddedBackground != "#383E2A" || Builtin("light_modern").Palette().DeletedText != "#FFA3A3" {
		t.Fatal("diff overlay composition changed")
	}
}

func TestScopeRulesMatchVSCodeReference(t *testing.T) {
	// Expected results are generated by the upstream vscode-textmate package, not
	// this resolver. Keep the generator beside the fixture for reproducibility.
	b, err := os.ReadFile("testdata/vscode-textmate.json")
	if err != nil {
		t.Fatal(err)
	}
	var fixture struct {
		TokenColors []rawToken `json:"tokenColors"`
		Cases       []struct {
			Scopes []string  `json:"scopes"`
			Color  string    `json:"color"`
			Font   FontStyle `json:"font"`
		} `json:"cases"`
	}
	if err = json.Unmarshal(b, &fixture); err != nil {
		t.Fatal(err)
	}
	th := &Theme{syntax: compileTokens(fixture.TokenColors), palette: Palette{Foreground: "#BBBBBB", Background: "#1E1E1E"}}
	for _, tc := range fixture.Cases {
		style := th.Resolve(tc.Scopes)
		if style.Color != tc.Color || style.Font != tc.Font {
			t.Errorf("%v: %+v, want %s font %d", tc.Scopes, style, tc.Color, tc.Font)
		}
	}
}

func TestTransparentFocusBorderDoesNotHideActiveText(t *testing.T) {
	dir := t.TempDir()
	file := writeTheme(t, dir, "transparent-focus.json", `{"colors":{"sideBar.background":"#121212","focusBorder":"#00000000","activityBar.foreground":"#FFFFFF","activityBarTop.foreground":"#4d9375","list.highlightForeground":"#abcdef","textLink.foreground":"#123456"}}`)
	p := mustLoad(t, file).Palette()
	if p.FocusBorder != p.Panel || p.NavigationForeground != "#4D9375" || p.Accent != "#123456" {
		t.Fatalf("focus border leaked into active text: %+v", p)
	}
}

func TestTerminalPopupSeparatesVitesseBlackSurfaces(t *testing.T) {
	dir := t.TempDir()
	file := writeTheme(t, dir, "black.json", `{"colors":{"editor.background":"#000","editor.foreground":"#AAA","quickInput.background":"#000","quickInput.foreground":"#DBD7CA","quickInputList.focusBackground":"#121212","quickInputList.focusForeground":"#FFFFEE","input.border":"#191919","focusBorder":"#00000000"}}`)
	p := mustLoad(t, file).Palette()
	if p.Background != "#000000" || p.Popup != "#000000" || p.PopupForeground != "#DBD7CA" || p.PopupSelectionForeground != "#FFFFEE" {
		t.Fatal("popup used editor/list text colors instead of quick input colors")
	}
	if contrast(p.PopupBorder, p.Popup) < 1.6 || p.PopupSelection != "#121212" {
		t.Fatalf("terminal widget is indistinguishable: border=%s selected=%s", p.PopupBorder, p.PopupSelection)
	}
}

func TestQuickInputUsesWidgetAndListFallbacks(t *testing.T) {
	dir := t.TempDir()
	file := writeTheme(t, dir, "fallback.json", `{"type":"light","colors":{"editor.foreground":"#000","foreground":"#123456","editorWidget.foreground":"#234567","list.activeSelectionForeground":"#FFFFFF","list.activeSelectionBackground":"#0060C0"}}`)
	p := mustLoadKind(t, file, "vs").Palette()
	if p.PopupForeground != "#234567" || p.PopupSelectionForeground != "#FFFFFF" {
		t.Fatal("quick input fallback confused editor, widget, or focused list foreground")
	}
}

