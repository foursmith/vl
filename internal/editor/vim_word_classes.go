func wordClass(r rune) int {
	if r < 0x100 {
		switch {
		case r == 0 || r == ' ' || r == '\t' || r == '\n' || r == 0xa0:
			return 0
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9',
			r == '_', r == 0xb5, r >= 0xc0:
			return 2
		default:
			return 1
		}
	}
	i := sort.Search(len(vimWordClasses), func(i int) bool {
		return vimWordClasses[i].last >= r
	})
	if i < len(vimWordClasses) && vimWordClasses[i].first <= r {
		return vimWordClasses[i].class
	}
	return 2
}
